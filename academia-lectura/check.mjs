import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./dist/index.html',import.meta.url),'utf8');
const data=html.match(/<script id="book-data" type="application\/json">([\s\S]*?)<\/script>/)[1];
const code=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
new vm.Script(code);
const nodes=new Map();
function node(id){if(!nodes.has(id))nodes.set(id,{textContent:id==='book-data'?data:'',innerHTML:'',value:'',dataset:{},classList:{add(){},remove(){},toggle(){}},setAttribute(){},addEventListener(){},click(){},showModal(){this.open=true},close(){this.open=false}});return nodes.get(id);}
const storage=new Map();
const ctx=vm.createContext({document:{getElementById:node,querySelectorAll:()=>[],createElement:()=>({click(){}})},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},window:{scrollTo(){}},setTimeout:()=>0,clearTimeout(){},Date,Blob,URL,console,confirm:()=>true});
vm.runInContext(code,ctx);
assert.equal(vm.runInContext('BOOKS.length',ctx),12);
assert.equal(vm.runInContext('LEADERS.length',ctx),6);
assert.equal(vm.runInContext('PROMPTS.length',ctx),9);
assert.equal(vm.runInContext('BOOKS.every(b=>b.title&&b.author&&b.points.length>=5&&b.url.startsWith("https://"))',ctx),true);
assert.equal(vm.runInContext('LEADERS.every(l=>BOOKS.some(b=>b.id===l.current)&&BOOKS.some(b=>b.id===l.next))',ctx),true);
assert.equal(vm.runInContext('filterBooks().length',ctx),12);
vm.runInContext('query="psicologia";',ctx);
assert.equal(vm.runInContext('filterBooks()[0].id',ctx),'07');
vm.runInContext('query="";category="Ventas";',ctx);
assert.equal(vm.runInContext('filterBooks().length',ctx),2);
vm.runInContext('category="Todos";patch("01",{status:"reading",notes:["Primera reflexión",...Array(8).fill("")]});',ctx);
assert.equal(vm.runInContext('entry("01").status',ctx),'reading');
assert.equal(vm.runInContext('entry("01").notes[0]',ctx),'Primera reflexión');
vm.runInContext('model.leader="jose"',ctx);
assert.equal(vm.runInContext('entry("01").notes[0]',ctx),'');
